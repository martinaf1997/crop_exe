# FIX: previously RP/RD were indexed by position (file_RP[i]), which silently
# mismatches when the three lists differ in length or order. Now we build the
# index from the RS files only and note when counterparts are missing.
uid_to_files: dict = {}
study_UIDS:   list = []

for rs_path in file_RS:
    parts = rs_path.split('/')
    uid = parts[-2] if parts[-2] == parts[-3] else f"{parts[-3]}_{parts[-2]}"

    # Find matching RP / RD by sharing the same parent folder
    parent = os.path.dirname(rs_path)
    rp_match = next((f for f in file_RP if os.path.dirname(f) == parent), None)
    rd_match = next((f for f in file_RD if os.path.dirname(f) == parent), None)

    uid_to_files[uid] = {"RS": rs_path, "RP": rp_match, "RD": rd_match}
    study_UIDS.append(uid)

    if rp_match is None: print(f"⚠️  No RP found for {uid}")
    if rd_match is None: print(f"⚠️  No RD found for {uid}")


