def trova_file_con_prefisso(cartella_base: str, prefisso: str) -> list[str]:
    """Recursively find all files whose name starts with *prefisso*."""
    return [
        os.path.join(root, f)
        for root, _, files in os.walk(cartella_base)
        for f in files
        if f.startswith(prefisso)
    ]


def ottieni_file_da_uid(uid_to_files: dict, study_uid: str, file_type: str) -> str:
    """Return the path for *file_type* ('RS', 'RP', or 'RD') of *study_uid*."""
    if study_uid not in uid_to_files:
        raise ValueError(f"StudyInstanceUID '{study_uid}' not found.")
    if file_type not in {"RS", "RP", "RD"}:
        raise ValueError(f"File type '{file_type}' invalid. Use 'RS', 'RP', or 'RD'.")
    path = uid_to_files[study_uid].get(file_type)
    if not path:
        raise ValueError(f"No '{file_type}' file for '{study_uid}'.")
    return path


def riordina_liste(lista1: list, lista2: list) -> tuple[list, list]:
    """
    Interactively reorder two parallel lists.
    The user assigns a new position index to each element of lista1;
    lista2 is reordered identically.
    """
    print("Lista 1:", lista1)
    print("Lista 2:", lista2)
    nuovi_indici = []
    for i, elem in enumerate(lista1):
        while True:
            try:
                idx = int(input(
                    f"New position for '{elem}' (0–{len(lista1)-1}): "
                ))
                if 0 <= idx < len(lista1) and idx not in nuovi_indici:
                    nuovi_indici.append(idx)
                    break
                print("Invalid or already-used index — try again.")
            except ValueError:
                print("Please enter an integer.")
    lista1_ord = [lista1[i] for i in nuovi_indici]
    lista2_ord = [lista2[i] for i in nuovi_indici]
    print("Reordered Lista 1:", lista1_ord)
    print("Reordered Lista 2:", lista2_ord)
    return lista1_ord, lista2_ord


