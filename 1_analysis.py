# Dose-based target identification
# ══════════════════════════════════════════════════════════════════════════════

def calcola_target_da_dose(uid_to_files: dict, studyUID: str, prs: float) -> list:
    """
    Identify target ROIs by comparing mean voxel dose to 50% of prescription.
    Falls back to name-matching (PTV / CTV) if no ROI meets the dose threshold.
    """
    rs = pydicom.dcmread(ottieni_file_da_uid(uid_to_files, studyUID, 'RS'))
    rd = pydicom.dcmread(ottieni_file_da_uid(uid_to_files, studyUID, 'RD'))

    dose_grid = rd.pixel_array * rd.DoseGridScaling
    dose_shape = dose_grid.shape
    ipp = np.array(rd.ImagePositionPatient, dtype=float)
    spacing = np.array([
        float(rd.PixelSpacing[0]),
        float(rd.PixelSpacing[1]),
        float(rd.GridFrameOffsetVector[1] - rd.GridFrameOffsetVector[0]),
    ])

    roi_names = {roi.ROINumber: roi.ROIName.upper() for roi in rs.StructureSetROISequence}
    targets = []

    for roi_contour in rs.ROIContourSequence:
        if not hasattr(roi_contour, 'ContourSequence'):
            continue
        voxels = []
        for contour in roi_contour.ContourSequence:
            coords = np.array(contour.ContourData).reshape(-1, 3)
            indices = np.round((coords - ipp) / spacing).astype(int)
            for idx in indices:
                z, y, x = idx[::-1]
                if 0 <= z < dose_shape[0] and 0 <= y < dose_shape[1] and 0 <= x < dose_shape[2]:
                    voxels.append(dose_grid[z, y, x])
        if voxels and np.mean(voxels) >= 0.5 * prs:
            targets.append(roi_contour.ReferencedROINumber)

    if not targets:
        print("  Fallback: matching by structure name (PTV/CTV)")
        targets = [
            num for num, name in roi_names.items()
            if re.search(r'\b(PTV|CTV)\b', name)
        ]

    return targets


def get_mean_dose_per_roi(uid_to_files: dict, studyUID: str,
                          roi_numbers: list | None = None) -> dict:
    """
    Return {roi_number_str: mean_dose}.
    Uses DVHSequence when available, otherwise falls back to voxel sampling.
    """
    rd = pydicom.dcmread(ottieni_file_da_uid(uid_to_files, studyUID, 'RD'))

    # Fast path: DVHSequence
    if hasattr(rd, 'DVHSequence'):
        return {
            str(dvh.DVHReferencedROISequence[0].ReferencedROINumber): float(dvh.DVHMeanDose)
            for dvh in rd.DVHSequence
            if roi_numbers is None
               or str(dvh.DVHReferencedROISequence[0].ReferencedROINumber) in roi_numbers
        }

    # Voxel-based fallback
    rs = pydicom.dcmread(ottieni_file_da_uid(uid_to_files, studyUID, 'RS'))
    dose_grid = rd.pixel_array * rd.DoseGridScaling
    dose_shape = dose_grid.shape
    ipp = np.array(rd.ImagePositionPatient, dtype=float)
    spacing = np.array([
        float(rd.PixelSpacing[0]),
        float(rd.PixelSpacing[1]),
        float(rd.GridFrameOffsetVector[1] - rd.GridFrameOffsetVector[0]),
    ])

    mean_doses = {}
    for roi_contour in rs.ROIContourSequence:
        roi_num = str(roi_contour.ReferencedROINumber)
        if roi_numbers is not None and roi_num not in roi_numbers:
            continue
        if not hasattr(roi_contour, 'ContourSequence'):
            continue
        voxels = []
        for contour in roi_contour.ContourSequence:
            coords = np.array(contour.ContourData).reshape(-1, 3)
            indices = np.round((coords - ipp) / spacing).astype(int)
            for idx in indices:
                z, y, x = idx[::-1]
                if 0 <= z < dose_shape[0] and 0 <= y < dose_shape[1] and 0 <= x < dose_shape[2]:
                    voxels.append(dose_grid[z, y, x])
        if voxels:
            mean_doses[roi_num] = float(np.mean(voxels))

    return mean_doses


