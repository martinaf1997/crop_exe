# Step 3 — Filter to CTV/ITV/PTV only; pair them up
# ══════════════════════════════════════════════════════════════════════════════

KEYWORDS = {'CTV', 'PTV', 'ITV'}

# Exact upper-cased names to exclude even if they contain a keyword.
# Add any other names you want globally ignored here.
EXCLUDED_NAMES = {'CTV_IN'}

# Keep only ROIs whose name contains a known keyword AND is not excluded.
# The exclusion check uses startswith so "CTV_in", "CTV_IN", "CTV_in_something"
# are all caught regardless of capitalisation or trailing characters.
filtered = {}
for key, value in study_to_target.items():
    pairs = [
        (n, num) for n, num in zip(value["Name"], value["Number"])
        if any(k in n.upper() for k in KEYWORDS)
        and not any(n.upper() == ex or n.upper().startswith(ex + '_') for ex in EXCLUDED_NAMES)
    ]
    if pairs:
        names, numbers = zip(*pairs)
        filtered[key] = {**value, "Name": list(names), "Number": list(numbers)}

# If ITV is present, drop CTV (ITV supersedes CTV)
for key, value in filtered.items():
    names, numbers = value["Name"], value["Number"]
    if any("ITV" in n.upper() for n in names):
        pairs = [(n, num) for n, num in zip(names, numbers) if "CTV" not in n.upper()]
        if pairs:
            names, numbers = zip(*pairs)
            filtered[key]["Name"]   = list(names)
            filtered[key]["Number"] = list(numbers)

display(pd.DataFrame.from_dict(filtered, orient="index"))

# Separate ITV/CTV from PTV and check counts match
final_clean_data:    dict = {}
mismatched_data:     dict = {}

for key, value in filtered.items():
    names, numbers = value["Name"], value["Number"]
    itv_ctv = [(n, num) for n, num in zip(names, numbers) if "CTV" in n.upper() or "ITV" in n.upper()]
    ptv     = [(n, num) for n, num in zip(names, numbers) if "PTV" in n.upper()]

    base = {"Prescription": value["Prescription"], "Plan": value["Plan"],
            "ITV/CTV": [x[0] for x in itv_ctv], "ITV/CTV_Number": [x[1] for x in itv_ctv],
            "PTV":     [x[0] for x in ptv],      "PTV_Number":     [x[1] for x in ptv]}

    if len(itv_ctv) == len(ptv):
        final_clean_data[key] = base
    else:
        mismatched_data[key] = base

# Auto-resolve mismatches: pick the top-N highest-dose PTVs
fixed_mismatched: dict = {}

for studyUID, value in mismatched_data.items():
    itv_ctv_list    = value["ITV/CTV"]
    itv_ctv_numbers = value["ITV/CTV_Number"]
    ptv_list        = value["PTV"]
    ptv_numbers     = value["PTV_Number"]
    n_needed        = len(itv_ctv_list)

    ptv_doses = get_mean_dose_per_roi(uid_to_files, studyUID,
                                      roi_numbers=[str(n) for n in ptv_numbers])

    if ptv_doses:
        top_ptv = sorted(ptv_doses, key=ptv_doses.get, reverse=True)[:n_needed]
        sel_names = [n for n, num in zip(ptv_list, ptv_numbers) if str(num) in top_ptv]
    else:
        print(f"No dose data for PTVs in {studyUID} — manual selection required")
        sel_names = []
        top_ptv   = []

    if len(itv_ctv_list) == len(sel_names):
        fixed_mismatched[studyUID] = {
            **value,
            "PTV": sel_names,
            "PTV_Number": top_ptv,
        }
    else:
        # Manual fallback
        print(f"\n⚠️  MISMATCH in {studyUID}")
        print(f"  ITV/CTV:  {itv_ctv_list}  {itv_ctv_numbers}")
        print(f"  PTV:      {ptv_list}  {ptv_numbers}")

        itv_ctv_list    = input("Select ITV/CTV names (comma-separated): ").split(',')
        itv_ctv_numbers = input("Select ITV/CTV numbers (comma-separated): ").split(',')
        sel_names       = input("Select PTV names (comma-separated): ").split(',')
        top_ptv         = input("Select PTV numbers (comma-separated): ").split(',')

        fixed_mismatched[studyUID] = {
            "Prescription": value["Prescription"], "Plan": value["Plan"],
            "ITV/CTV": itv_ctv_list, "ITV/CTV_Number": itv_ctv_numbers,
            "PTV": sel_names, "PTV_Number": top_ptv,
        }

final_clean_data.update(fixed_mismatched)
