def _crop_record() -> dict:
    return {
        "Plan": None, "Prescription": None,
        "ITV/CTV": None, "ITV/CTV ID": None,
        "PTV": None, "PTV ID": None,
        "Expansion (mm)": None, "Crop": None,
        "Max crop distance (mm)": None, "Cropped voxels (%)": None,
    }


def _analyse_pair(study_key: str, row: pd.Series, contour,
                  ctv_name: str, ctv_num, ptv_name: str, ptv_num,
                  study_to_crop: dict) -> None:
    """Compute expansion / crop stats for one CTV–PTV pair and write to study_to_crop."""
    rec = _crop_record()
    rec["Plan"]         = row["Plan"]
    rec["Prescription"] = row["Prescription"]
    rec["ITV/CTV"]      = ctv_name
    rec["ITV/CTV ID"]   = ctv_num
    rec["PTV"]          = ptv_name
    rec["PTV ID"]       = ptv_num

    print(f"  CTV/ITV: {ctv_name} (#{ctv_num})  |  PTV: {ptv_name} (#{ptv_num})")

    pti_ctv = extract_contour_points(contour, ctv_num)
    pti_ptv = extract_contour_points(contour, ptv_num)

    if not pti_ctv or not pti_ptv:
        print(f"  ⚠️  Empty contour data for {study_key} — skipping")
        study_to_crop[study_key] = rec
        return

    S1 = np.array(pti_ctv).reshape(-1, 3)
    S2 = np.array(pti_ptv).reshape(-1, 3)

    exp, cropped, max_crop = process_struct(S1, S2)

    rec["Expansion (mm)"] = round(exp)
    crop_frac = len(cropped) / len(S2) if len(S2) > 0 else 0

    if crop_frac > CROP_THRESHOLD:
        print(f"  🔶 Likely cropped — {round(crop_frac * 100)}% of PTV points cropped\n")
        rec["Crop"] = 'Yes'
        rec["Max crop distance (mm)"]  = round(max_crop)
        rec["Cropped voxels (%)"]      = round(crop_frac * 100)
    else:
        print(f"  ✔  Not cropped\n")
        rec["Crop"] = 'No'
        rec["Max crop distance (mm)"]  = '-'
        rec["Cropped voxels (%)"]      = '-'

    study_to_crop[study_key] = rec


