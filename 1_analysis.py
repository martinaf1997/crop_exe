def process_struct(S1: np.ndarray, S2: np.ndarray) -> tuple[float, list, float]:
    """
    Compute the expected CTV→PTV expansion and detect cropped PTV points.

    Parameters
    ----------
    S1 : (N,3) array — CTV contour points (x, y, z) in mm
    S2 : (N,3) array — PTV contour points

    Returns
    -------
    expected_expansion : float   — modal positive distance S2→S1 boundary
    cropped_points     : list    — distances below 80 % of expected expansion
    max_crop           : float   — largest missing margin in mm
    """
    z_values = np.unique(np.concatenate((S1[:, 2], S2[:, 2])))
    dist = []

    for z in z_values:
        slice_S1 = S1[np.isclose(S1[:, 2], z)]
        slice_S2 = S2[np.isclose(S2[:, 2], z)]

        if len(slice_S1) < 3:
            continue

        poly = Polygon(slice_S1[:, :2])
        if not poly.is_valid:
            poly = poly.buffer(0)   # attempt auto-repair

        for pt in slice_S2:
            point2D = Point(pt[0], pt[1])
            d = point2D.distance(poly.exterior)
            if poly.contains(point2D):
                d = -d
            dist.append(d)

    if not dist:
        return 0.0, [], 0.0

    positive_dists = [d for d in dist if d > 0]
    if not positive_dists:
        return 0.0, [], 0.0

    expected_expansion = float(stats.mode(positive_dists, axis=None)[0])
    print(f"  Expected expansion: {round(expected_expansion)} mm")

    cropped_points = [d for d in dist if d < expected_expansion * 0.8]
    max_crop = (expected_expansion - min(cropped_points)) if cropped_points else 0.0

    return expected_expansion, cropped_points, max_crop


def extract_contour_points(contour_seq, roi_number: int) -> list:
    """Pull flat ContourData list for a given ROI number from ROIContourSequence."""
    points = []
    for m in contour_seq:
        if m.ReferencedROINumber == roi_number:
            for cs in m.ContourSequence:
                points.extend(cs.ContourData)
    return points


