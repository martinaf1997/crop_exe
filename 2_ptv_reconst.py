def expand_structure_3d(rtstruct, roi_name: str,
                        expansion_mm: float,
                        voxel_spacing: list[float]) -> np.ndarray:
    """
    Expand an RTStruct ROI by *expansion_mm* in real millimetres (3-D).

    Uses a signed-distance-field approach so the expansion is isotropic in
    physical space regardless of anisotropic voxel spacing.

    Parameters
    ----------
    rtstruct       : rt_utils RTStruct object
    roi_name       : name of the source ROI (CTV / ITV)
    expansion_mm   : margin to add in mm
    voxel_spacing  : [row_mm, col_mm, slice_mm]  (x, y, z)

    Returns
    -------
    expanded_mask : bool ndarray with the same shape as the CT volume
    """
    mask = rtstruct.get_roi_mask_by_name(roi_name)

    # Distance from every *outside* voxel to the ROI surface
    dist_outside = distance_transform_edt(~mask, sampling=voxel_spacing)
    # Distance from every *inside* voxel to the ROI surface
    dist_inside  = distance_transform_edt( mask, sampling=voxel_spacing)

    # Signed distance: positive inside, negative outside
    signed_dist = dist_inside - dist_outside

    # Include voxels within expansion_mm of the surface (on the outside)
    return signed_dist >= -expansion_mm


def compute_voxel_spacing(ct_files: list[str]) -> list[float]:
    """
    Derive (x, y, z) voxel spacing from the CT series.

    BUGFIX (root cause of insufficient cranio-caudal expansion): z spacing
    used to be computed from ct_files[0] and ct_files[1] straight out of the
    caller's `sorted(os.listdir(...))` call. That sort is ALPHABETICAL ON
    FILENAME — and CT filenames are DICOM SOPInstanceUIDs, which have no
    relationship to slice position in space. So the "first two" files were
    essentially two RANDOM slices, not physically adjacent ones, and the
    z_spacing derived from their ImagePositionPatient difference could be
    off by an order of magnitude (e.g. 66 mm estimated instead of a true
    3 mm slice spacing). Since expand_structure_3d() uses this value as the
    physical sampling for the 3-D distance transform, an inflated z_spacing
    makes each z-step "worth" far more physical mm than it really is, so
    the isotropic mm margin gets satisfied after far fewer slices — the
    expansion silently stops short in the cranio-caudal direction while
    still being correct in-plane (X/Y), exactly the pattern of the rebuilt
    PTV closely hugging the CTV on sagittal/coronal views.

    Fix: sort ALL slices by their actual ImagePositionPatient Z coordinate
    (not filename), then take the MEDIAN of consecutive z-gaps — robust to
    a missing/duplicated slice here or there, unlike using just two files.
    """
    datasets = [pydicom.dcmread(f, stop_before_pixels=True) for f in ct_files]
    datasets.sort(key=lambda ds: float(ds.ImagePositionPatient[2]))

    first = datasets[0]
    xy = [float(x) for x in first.PixelSpacing]

    if len(datasets) >= 2:
        z_positions = [float(ds.ImagePositionPatient[2]) for ds in datasets]
        z_diffs = np.abs(np.diff(z_positions))
        z_spacing = float(np.median(z_diffs))
        if z_spacing == 0 or np.any(z_diffs > 3 * z_spacing):
            print(f"  ⚠️  Irregular slice spacing detected (gaps: "
                  f"{np.round(np.unique(z_diffs), 2)} mm) — check for duplicate/missing slices")
    else:
        z_spacing = float(first.SliceThickness)

    return xy + [z_spacing]


def plot_3d_mask(mask: np.ndarray, color: str = 'red', alpha: float = 0.5):
    """Return a Poly3DCollection mesh for the given boolean mask (for QA plots)."""
    verts, faces, _, _ = measure.marching_cubes(mask, level=0.5)
    mesh = Poly3DCollection(verts[faces], alpha=alpha)
    mesh.set_facecolor(color)
    return mesh


def _fix_roi_numbers(rtstruct, roi_name: str) -> bool:
    """
    After rt_utils adds a new ROI it may assign a ROINumber that is a
    DUPLICATE of an already-existing ROI (e.g. it reuses the CTV's number).
    This function gives the new ROI a truly unique number and re-links
    every DICOM sequence that references it by ROI number.

    BUGFIX (root cause of "3_coverage_scores doesn't see the new expanded
    contour"): rt_utils always *appends* the new ROI's entries at the END
    of StructureSetROISequence / ROIContourSequence / RTROIObservationsSequence.
    When the assigned number collides with an existing ROI, there are TWO
    entries in ROIContourSequence sharing that duplicate number: the
    pre-existing one (earlier in the sequence) and the brand-new expanded
    contour (the one just appended, i.e. LAST). The previous version of
    this function scanned the sequence FORWARDS and re-linked the FIRST
    match — which is the *pre-existing* ROI, not the new one. The result:
    the new "<PTV>_rebuilt" ROI ended up pointing at someone else's old
    contour (e.g. the CTV's), while the actual expanded-mask contour data
    was left orphaned under the stale duplicate number. Coverage scoring
    downstream then silently read the wrong (unexpanded) geometry instead
    of raising an error.

    Fix: scan each sequence in REVERSE so the LAST (i.e. newly appended)
    matching entry is the one re-linked, leaving the pre-existing ROI's
    entry untouched.

    Returns True on success, False if the ROI was not found.
    """
    # Find old (possibly duplicate) number assigned by rt_utils
    old_number = None
    for roi in rtstruct.ds.StructureSetROISequence:
        if roi.ROIName == roi_name:
            old_number = roi.ROINumber
            break

    if old_number is None:
        return False

    # Assign a truly unique number
    used = {roi.ROINumber for roi in rtstruct.ds.StructureSetROISequence
            if roi.ROIName != roi_name}
    new_number = 1
    while new_number in used:
        new_number += 1

    if new_number == old_number:
        return True  # already unique, nothing to do

    # Update StructureSetROISequence (the new ROI's own entry — unique by name)
    for roi in rtstruct.ds.StructureSetROISequence:
        if roi.ROIName == roi_name:
            roi.ROINumber = new_number
            break

    # Update ROIContourSequence — the new ROI's contour was appended LAST,
    # so scan in reverse to grab it instead of an earlier, pre-existing
    # ROI that happens to share the same (duplicate) number.
    updated_contour = False
    for roi_contour in reversed(rtstruct.ds.ROIContourSequence):
        if roi_contour.ReferencedROINumber == old_number and not updated_contour:
            roi_contour.ReferencedROINumber = new_number
            updated_contour = True

    if not updated_contour:
        print(f"  ⚠️  No ROIContour entry found for ROI number {old_number}")

    # Update RTROIObservationsSequence too, for DICOM consistency (some
    # viewers / downstream tools key off this sequence as well). Same
    # duplicate-number issue, same reverse-scan fix.
    updated_obs = False
    if hasattr(rtstruct.ds, 'RTROIObservationsSequence'):
        for obs in reversed(rtstruct.ds.RTROIObservationsSequence):
            if obs.ReferencedROINumber == old_number and not updated_obs:
                obs.ReferencedROINumber = new_number
                updated_obs = True

    return updated_contour


