df_uidtofiles = pd.read_excel(MAINFOLDER + 'uid_to_files_new.xlsx',    index_col=0, engine='openpyxl')
df_crop       = pd.read_excel(MAINFOLDER + 'crop_analysis_new.xlsx',   index_col=0, engine='openpyxl')

display(df_uidtofiles)
display(df_crop)

for index, row in df_crop.iterrows():
    # Normalise index: strip trailing "_n?" suffix to get the base UID key
    base_uid = index[:-3] if index[-3:-1] == '_n' else index

    if row['Crop'] != 'Yes':
        continue

    print(f"\n── {index}")
    try:
        fileRS    = df_uidtofiles.loc[base_uid, 'RS']
        rs_folder = os.path.dirname(fileRS)
        dest_folder = os.path.join(MAINFOLDER, 'rebuilt', str(index))

        # ── Build sorted CT file list (reads from original, no copy) ───────
        ct_files = sorted([
            os.path.join(rs_folder, f)
            for f in os.listdir(rs_folder)
            if f.startswith('CT.') and f.endswith('.dcm')
        ])
        if not ct_files:
            print(f"  ⚠️  No CT files found for {index} — skipping")
            continue

        # ── Copy only plan files to dest_folder — no CTs ─────────────────
        # Copying the full CT series (often 100s of files) doubles disk usage.
        # We only need RP, RD, and the new rebuilt RS in the output folder.
        os.makedirs(dest_folder, exist_ok=True)
        plan_prefixes = ('RP', 'RTP', 'RD', 'RTD', 'RS', 'RTS')
        for f in os.listdir(rs_folder):
            if any(f.startswith(p) for p in plan_prefixes):
                shutil.copy(os.path.join(rs_folder, f), dest_folder)

        # Remove the original RS — will be replaced by RS.rebuilt.dcm
        old_rs_files = (
            glob(os.path.join(dest_folder, 'RS*.dcm')) +
            glob(os.path.join(dest_folder, 'RTS*.dcm'))
        )
        if not old_rs_files:
            print(f"  ⚠️  No RS/RTS file to remove in {dest_folder} — skipping")
            continue
        os.remove(old_rs_files[0])

        # ── RTStructBuilder needs a folder with ONLY CT files ─────────────
        # Google Drive does not support symlinks, so we copy the CTs here.
        # dest_folder contains only plan files (RP, RD, rebuilt RS), so
        # this is still just one copy of the CTs total — not two.
        ct_only_folder = os.path.join(dest_folder, 'ct_only')
        os.makedirs(ct_only_folder, exist_ok=True)
        for ct_path in ct_files:
            dest_ct = os.path.join(ct_only_folder, os.path.basename(ct_path))
            if not os.path.exists(dest_ct):
                shutil.copy(ct_path, dest_ct)

        # ── Load RTStruct ──────────────────────────────────────────────────
        rtstruct = RTStructBuilder.create_from(
            dicom_series_path=ct_only_folder,
            rt_struct_path=fileRS,
        )

        ctv_name      = row['ITV/CTV']
        expansion_mm  = float(row['Expansion (mm)'])
        new_roi_name  = row['PTV'] + '_rebuilt'  # defined early so it's available in error messages

        # ── Voxel spacing (uses ImagePositionPatient for z, more reliable) ─
        voxel_spacing = compute_voxel_spacing(ct_files)
        print(f"  ℹ️  voxel spacing (row, col, z) mm: "
              f"[{voxel_spacing[0]:.3f}, {voxel_spacing[1]:.3f}, {voxel_spacing[2]:.3f}]")

        # ── 3-D expansion ──────────────────────────────────────────────────
        expanded_mask = expand_structure_3d(rtstruct, ctv_name, expansion_mm, voxel_spacing)

        if not np.any(expanded_mask):
            print(f"  ❌ Expanded mask for {new_roi_name} is empty — skipping")
            continue

        # ── Add new ROI ────────────────────────────────────────────────────
        rtstruct.add_roi(mask=expanded_mask, color=[255, 0, 0], name=new_roi_name)

        # ── Fix potentially duplicate ROI number assigned by rt_utils ──────
        if not _fix_roi_numbers(rtstruct, new_roi_name):
            print(f"  ❌ Could not find {new_roi_name} in StructureSetROISequence — skipping")
            continue

        # ── Save ───────────────────────────────────────────────────────────
        output_file = os.path.join(dest_folder, 'RS.rebuilt.dcm')
        rtstruct.save(output_file)

        # ── Sanity check ──────────────────────────────────────────────────
        # Re-read the file just written and make sure the new ROI is really
        # linked to its own (expanded) contour, not to another structure's.
        # This is what would have caught the ROI-numbering bug earlier:
        # previously the "_rebuilt" ROI could silently end up pointing at
        # the CTV's original (unexpanded) contour.
        check_ds = pydicom.dcmread(output_file)
        new_roi_number = next(
            (r.ROINumber for r in check_ds.StructureSetROISequence
             if r.ROIName == new_roi_name), None
        )
        new_contour_seq = next(
            (rc.ContourSequence for rc in check_ds.ROIContourSequence
             if rc.ReferencedROINumber == new_roi_number and hasattr(rc, 'ContourSequence')),
            None
        )
        ctv_roi_number = next(
            (r.ROINumber for r in check_ds.StructureSetROISequence
             if r.ROIName == ctv_name), None
        )
        ctv_contour_seq = next(
            (rc.ContourSequence for rc in check_ds.ROIContourSequence
             if rc.ReferencedROINumber == ctv_roi_number and hasattr(rc, 'ContourSequence')),
            None
        )
        if new_contour_seq is None:
            print(f"  ❌ Sanity check FAILED: {new_roi_name} has no linked contour in the saved file!")
        elif ctv_contour_seq is not None and new_contour_seq is ctv_contour_seq:
            print(f"  ❌ Sanity check FAILED: {new_roi_name} is linked to the SAME contour object as {ctv_name}!")
        else:
            n_new_points = sum(len(c.ContourData) for c in new_contour_seq)
            n_ctv_points = sum(len(c.ContourData) for c in ctv_contour_seq) if ctv_contour_seq else 0
            print(f"  ✔ Saved {new_roi_name}  →  {output_file}"
                  f"  (contour points: {n_new_points}, CTV: {n_ctv_points})")

    except Exception as e:
        print(f"  ❌ Error processing {index}: {e}")
        continue