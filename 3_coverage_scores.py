def _write_metrics(df: pd.DataFrame, index: str,
                   prefix: str, m: dict) -> None:
    """Write metric dict into the DataFrame row, rounding to 2 dp."""
    for key in ('V95', 'V90', 'D95', 'D90', 'D99', 'CCI'):
        df.loc[index, f'{key} {prefix}'] = round(m[key], 2)


for index, row in df_crop.iterrows():
    target      = row['PTV']
    target_ctv  = row['ITV/CTV']
    prescription = float(row['Prescription'])
    is_crop     = row['Crop']

    rebuilt_folder = os.path.join(MAINFOLDER, 'rebuilt', str(index))

    # ── Resolve RS path ──────────────────────────────────────────────────────
    try:
        if is_crop == 'Yes':
            # Use the rebuilt RS (ends with 'modified.dcm')
            rebuilt_rs_candidates = [
                s for s in trova_file_con_prefisso(rebuilt_folder, 'RS')
                if s.endswith('rebuilt.dcm')
            ]
            if not rebuilt_rs_candidates:
                print(f"⚠️  No rebuilt RS found for {index} — skipping")
                continue
            file_RS = rebuilt_rs_candidates[0]

            # Find the _rebuilt ROI name stored in this file
            structure_name = next(
                (k.ROIName for k in pydicom.dcmread(file_RS).StructureSetROISequence
                 if k.ROIName.endswith('_rebuilt')),
                None,
            )
            if structure_name is None:
                print(f"⚠️  No '_rebuilt' ROI in {file_RS} — skipping")
                continue
        else:
            match = [i for i in df_files.index if i in str(index) or str(index) in i]
            if not match:
                print(f"⚠️  No UID match for {index} in uid_to_files — skipping")
                continue
            file_RS = df_files.loc[match[0], 'RS']
            structure_name = target

        # ── Resolve RD path ──────────────────────────────────────────────────
        match = [i for i in df_files.index if i in str(index) or str(index) in i]
        if not match:
            print(f"⚠️  No UID match for {index} — skipping")
            continue
        file_RD = df_files.loc[match[0], 'RD']

        # ── Load dose ────────────────────────────────────────────────────────
        dose, spacing, origin, _ = load_dose(file_RD)

        # ── Metrics for CTV ──────────────────────────────────────────────────
        mask_ctv = extract_structure_mask(file_RS, dose.shape, spacing, origin, target_ctv)
        m_ctv    = compute_dvh_metrics(dose, mask_ctv, prescription)
        _write_metrics(df_crop, index, 'CTV', m_ctv)

        # ── Metrics for original PTV ─────────────────────────────────────────
        mask_ptv = extract_structure_mask(file_RS, dose.shape, spacing, origin, target)
        m_ptv    = compute_dvh_metrics(dose, mask_ptv, prescription)
        _write_metrics(df_crop, index, 'PTV', m_ptv)

        # ── Metrics for rebuilt PTV (hPTV) ───────────────────────────────────
        mask_hptv = extract_structure_mask(file_RS, dose.shape, spacing, origin, structure_name)
        m_hptv    = compute_dvh_metrics(dose, mask_hptv, prescription)
        _write_metrics(df_crop, index, 'hPTV', m_hptv)

        print(f"✔ {index}")

    except Exception as e:
        print(f"❌ Error in {index}: {e}")

