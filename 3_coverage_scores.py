def trova_file_con_prefisso(cartella_base: str, prefisso: str) -> list[str]:
    """Recursively find all files whose name starts with *prefisso*."""
    return [
        os.path.join(root, f)
        for root, _, files in os.walk(cartella_base)
        for f in files
        if f.startswith(prefisso)
    ]


def load_dose(dose_path: str) -> tuple[np.ndarray, list, list, object]:
    """
    Load an RTDOSE file.

    Returns
    -------
    dose    : 3-D float array in Gy  (shape: slices × rows × cols)
    spacing : [x_mm, y_mm, z_mm]
    origin  : [x0, y0, z0] in mm (ImagePositionPatient)
    ds      : raw pydicom Dataset (for any extra attributes)
    """
    ds = pydicom.dcmread(dose_path)
    dose = ds.pixel_array.astype(float) * float(ds.DoseGridScaling)
    spacing = [
        float(ds.PixelSpacing[0]),
        float(ds.PixelSpacing[1]),
        float(ds.GridFrameOffsetVector[1]) - float(ds.GridFrameOffsetVector[0]),
    ]
    origin = [float(v) for v in ds.ImagePositionPatient]
    return dose, spacing, origin, ds


def extract_structure_mask(rtstruct_path: str,
                           dose_shape: tuple,
                           dose_spacing: list,
                           dose_origin: list,
                           structure_name: str) -> np.ndarray:
    """
    Rasterise an RT structure onto the dose grid.

    Returns a bool ndarray of shape *dose_shape* (slices × rows × cols).
    Raises ValueError if the structure is not found or has no contours.
    """
    ds = pydicom.dcmread(rtstruct_path)

    # Look up ROI number
    roi_number = next(
        (roi.ROINumber for roi in ds.StructureSetROISequence
         if roi.ROIName == structure_name),
        None,
    )
    if roi_number is None:
        raise ValueError(f"Structure '{structure_name}' not found in {rtstruct_path}.")

    # Get contour sequence
    contour_seq = next(
        (roi.ContourSequence for roi in ds.ROIContourSequence
         if roi.ReferencedROINumber == roi_number and hasattr(roi, 'ContourSequence')),
        None,
    )
    if contour_seq is None:
        raise ValueError(f"No contours for '{structure_name}'.")

    mask = np.zeros(dose_shape, dtype=bool)

    for contour in contour_seq:
        points  = np.array(contour.ContourData).reshape(-1, 3)
        z       = points[0, 2]
        z_index = int(round((z - dose_origin[2]) / dose_spacing[2]))

        if not (0 <= z_index < dose_shape[0]):
            continue

        # Patient → pixel coordinates (floating point for polygon path)
        x_px = (points[:, 0] - dose_origin[0]) / dose_spacing[0]
        y_px = (points[:, 1] - dose_origin[1]) / dose_spacing[1]

        poly_path = Path(np.column_stack((x_px, y_px)))

        # Build a grid of pixel centres and test containment
        xi, yi = np.meshgrid(np.arange(dose_shape[2]), np.arange(dose_shape[1]))
        coords  = np.column_stack((xi.ravel(), yi.ravel()))
        inside  = poly_path.contains_points(coords).reshape(dose_shape[1], dose_shape[2])

        mask[z_index] |= inside

    return mask


# ══════════════════════════════════════════════════════════════════════════════
# DVH metrics
# ══════════════════════════════════════════════════════════════════════════════

def compute_dvh_metrics(dose: np.ndarray, mask: np.ndarray,
                        prescribed_dose: float,
                        bin_size: float = BIN_SIZE) -> dict:
    """
    Compute DVH-based coverage metrics for a single structure.

    Returns a dict with keys:
        dvh_x, dvh_y  — cumulative DVH curve (for plotting)
        V95, V90      — volume fraction (%) receiving ≥ 95%/90% of prescription
        D95, D90, D99 — dose (Gy) at 95th/90th/99th percentile of coverage
        CCI           — conformity index  D99 / prescription
    """
    dose_vals = dose[mask].astype(float)
    if dose_vals.size == 0:
        nan = float('nan')
        return dict(dvh_x=np.array([]), dvh_y=np.array([]),
                    V95=nan, V90=nan, D95=nan, D90=nan, D99=nan, CCI=nan)

    # Cumulative DVH
    bins      = np.arange(0, dose_vals.max() + bin_size, bin_size)
    hist, edges = np.histogram(dose_vals, bins=bins)
    cumulative  = np.cumsum(hist[::-1])[::-1]
    dvh_y       = cumulative / cumulative[0] * 100
    dvh_x       = edges[:-1]

    n = dose_vals.size

    def _vx(threshold_gy: float) -> float:
        return float(np.sum(dose_vals >= threshold_gy) / n * 100)

    def _dx(percent: float) -> float:
        """Dose received by the highest-dose *percent* % of the volume."""
        sorted_desc = np.sort(dose_vals)[::-1]
        idx = min(int(np.ceil(percent / 100 * n)) - 1, n - 1)
        return float(sorted_desc[max(idx, 0)])

    v95 = _vx(0.95 * prescribed_dose)
    v90 = _vx(0.90 * prescribed_dose)
    d95 = _dx(95)
    d90 = _dx(90)
    d99 = _dx(99)

    return dict(
        dvh_x=dvh_x, dvh_y=dvh_y,
        V95=v95, V90=v90,
        D95=d95, D90=d90, D99=d99,
        CCI=d99 / prescribed_dose if prescribed_dose else float('nan'),
    )


